/** 章节所属课程 */
export const getCourseById = (id: number) => courses.find((c) => c.id === id)

/** 课程下的章节（已排序、已过滤未发布） */
export const getChaptersByCourse = (courseId: number) =>
  chapters
    .filter((c) => c.course_id === courseId && c.is_published === 1 && c.is_deleted === 0)
    .sort((a, b) => a.sort - b.sort)

/** 章节下的题目 */
export const getQuestionsByChapter = (chapterId: number) =>
  questions.filter((x) => x.chapter_id === chapterId && x.is_deleted === 0).sort((a, b) => a.sort - b.sort)

/** 章节下的动画 */
export const getAnimationsByChapter = (chapterId: number) =>
  animations.filter((a) => a.chapter_id === chapterId && a.is_deleted === 0).sort((a, b) => a.sort - b.sort)

/** 全站题目总数（首页统计用） */
export const totalQuestionCount = questions.length
export const totalChapterCount = chapters.length
