/* ------------------------------------------------------------------ 类型定义 */

export type StageType = '硬件预备基础' | 'PCB专项' | '嵌入式C' | 'STM32固件' | 'RTOS实战' | '综合实战' | '底层进阶'
export type QuestionType = '单选题' | '多选题' | '判断题' | '简答题'

/** 表1：course 课程总表 */
export interface Course {
  id: number
  course_name: string
  course_desc: string
  stage_type: StageType
  cover_image_url: string
  sort: number
  is_published: 0 | 1
  created_at: string
  updated_at: string
  is_deleted: 0 | 1
  /** 原型扩展：封面渐变色主题（无真实图片资源时用于占位） */
  cover_theme: 'blue' | 'cyan' | 'violet' | 'amber' | 'emerald' | 'rose' | 'sky'
}

/** 表2：chapter 章节表 */
export interface Chapter {
  id: number
  course_id: number
  chapter_name: string
  /** Markdown 讲义正文 */
  chapter_content: string
  sort: number
  is_published: 0 | 1
  created_at: string
  updated_at: string
  is_deleted: 0 | 1
  /** 原型扩展：预计阅读时长（分钟） */
  estimated_minutes: number
  /** 原型扩展：章节摘要，用于卡片展示 */
  summary: string
}

/** 表3：animation 交互式动画资源表 */
export interface Animation {
  id: number
  chapter_id: number
  anim_name: string
  anim_type: 'Konva' | 'SVG'
  anim_script: string
  anim_config: Record<string, number | string>
  sort: number
  is_deleted: 0 | 1
  /** 原型扩展：前端组件 key，决定渲染哪个 Konva 动画 */
  anim_key:
    | 'voltage-divider'
    | 'rc-charge'
    | 'pwm-wave'
    | 'adc-sample'
    | 'pointer-mem'
    | 'bit-register'
    | 'task-switch'
    | 'data-flow'
    | 'uart-timing'
    | 'bus-timing'
    | 'nvic-nest'
    | 'timer-base'
    | 'dma-transfer'
    | 'queue-block'
    | 'spi-dma'
    | 'notify-event'
    | 'sch-to-pcb'
    | 'dma-pingpong'
    | 'sw-timer'
    | 'burn-in'
    | 'boot-timeline'
    | 'clock-tree'
    | 'tail-chain'
    | 'mem-layout'
    | 'fault-stack'
    | 'bit-band'
  }

/** 表4：question 题库题目表 */
export interface Question {
  id: number
  chapter_id: number
  question_type: QuestionType
  question_title: string
  /** 选项，JSON 存储：[{ key: 'A', text: '...' }] */
  options: Array<{ key: string; text: string }>
  /** 参考答案：单选 'A'、多选 'ABC'、判断 'A'/'B'、简答为参考文字 */
  answer: string
  analysis: string
  score: number
  sort: number
  is_deleted: 0 | 1
}

