/** Fisher–Yates 洗牌（每次组卷随机） */
function shuffle<T>(arr: T[]): T[] {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** 按考卷预设组一套题：每个维度内部洗牌抽 perCategory 题，维度间穿插排列 */
export function buildPaper(meta: PaperMeta): AssessQuestion[] {
  const buckets = meta.categories.map((cat) =>
    shuffle(assessmentBank.filter((q) => q.category === cat)).slice(0, meta.perCategory),
  )
  // 穿插：每轮从各维度各取一题，避免同维度连排
  const out: AssessQuestion[] = []
  const maxLen = Math.max(0, ...buckets.map((b) => b.length))
  for (let i = 0; i < maxLen; i++) {
    for (const b of buckets) if (b[i]) out.push(b[i])
  }
  return out
}

export interface CategoryScore {
  category: AssessCategory
  correct: number
  total: number
}

export interface AssessResult {
  /** 归一化百分制得分 */
  score: number
  correct: number
  total: number
  perCategory: CategoryScore[]
  /** 答错的考点标签（去重），用于薄弱点提示 */
  weakTags: string[]
  /** 每题对错，与试卷题目一一对应 */
  perQuestion: Array<{ id: number; correct: boolean }>
}

/**
 * 客观题判分：单选/判断必须完全一致；多选多选、少选、错选均不得分。
 * answers 的键是题目 id（转字符串），值是用户提交的字母串。
 */
export function gradePaper(paper: AssessQuestion[], answers: Record<string, string>): AssessResult {
  const normalize = (s: string) =>
    (s || '')
      .replace(/[^A-Za-z]/g, '')
      .toUpperCase()
      .split('')
      .sort()
      .join('')

  const perQuestion = paper.map((q) => {
    const user = normalize(answers[String(q.id)])
    const right = normalize(q.answer)
    return { id: q.id, correct: user.length > 0 && user === right }
  })

  const cats = [...new Set(paper.map((q) => q.category))]
  const perCategory: CategoryScore[] = cats.map((cat) => {
    const qs = paper.filter((q) => q.category === cat)
    const correct = perQuestion.filter((r, i) => paper[i].category === cat && r.correct).length
    return { category: cat, correct, total: qs.length }
  })

  const correct = perQuestion.filter((r) => r.correct).length
  const weakTags = paper.filter((q, i) => !perQuestion[i].correct).map((q) => q.tag)

  return {
    score: Math.round((correct / paper.length) * 100),
    correct,
    total: paper.length,
    perCategory,
    weakTags: [...new Set(weakTags)],
    perQuestion,
  }
}

